#!/usr/bin/env python3
"""Build the distributable versions of the game from web/.

  dist/www/            one-file bundle (three.js included) + PWA files, used for
                       GitHub Pages and packaged into the Android app
  dist/artifact.html   single self-contained page that loads three.js from jsDelivr

Usage: python3 tools/build.py [--esbuild PATH]
esbuild is looked up in $ESBUILD, then PATH, then falls back to `npx esbuild`.
"""
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, 'web')
DIST = os.path.join(ROOT, 'dist')
VERSION = '1.1.0'
THREE_CDN = 'https://cdn.jsdelivr.net/npm/three@0.170.0/build/three.module.min.js'


def esbuild_cmd():
    if '--esbuild' in sys.argv:
        return [sys.argv[sys.argv.index('--esbuild') + 1]]
    env = os.environ.get('ESBUILD')
    if env:
        return [env]
    for cand in (shutil.which('esbuild'), '/opt/npm-tools/node_modules/.bin/esbuild'):
        if cand and os.path.exists(cand):
            return [cand]
    return ['npx', '--yes', 'esbuild@0.24.0']


def run(cmd):
    print('+', ' '.join(cmd))
    subprocess.run(cmd, check=True, cwd=ROOT)


def bundle(out, external_three):
    cmd = esbuild_cmd() + [
        'web/js/main.js', '--bundle', '--format=esm', '--minify', '--target=es2020',
        '--charset=utf8', f'--outfile={out}',
    ]
    if external_three:
        cmd.append('--external:three')
    else:
        cmd.append('--alias:three=./web/vendor/three.module.min.js')
    run(cmd)
    with open(os.path.join(ROOT, out), encoding='utf-8') as f:
        return f.read()


def build_www():
    out = os.path.join(DIST, 'www')
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(os.path.join(out, 'js'))
    shutil.copytree(os.path.join(WEB, 'icons'), os.path.join(out, 'icons'))
    shutil.copy(os.path.join(WEB, 'manifest.webmanifest'), out)
    js = bundle('dist/www/js/game.js', external_three=False)
    h = hashlib.sha1(js.encode()).hexdigest()[:10]
    with open(os.path.join(WEB, 'index.html'), encoding='utf-8') as f:
        html = f.read()
    html = re.sub(r'<script type="importmap">.*?</script>\s*', '', html, flags=re.S)
    html = html.replace('<script type="module" src="./js/main.js"></script>',
                        f'<script type="module" src="./js/game.js?v={h}"></script>\n'
                        '<script>if (\'serviceWorker\' in navigator && location.protocol === \'https:\' && !window.AndroidShell) '
                        'addEventListener(\'load\', () => navigator.serviceWorker.register(\'./sw.js\').catch(() => {}));</script>')
    with open(os.path.join(out, 'index.html'), 'w', encoding='utf-8') as f:
        f.write(html)
    files = ['./', './index.html', f'./js/game.js?v={h}', './manifest.webmanifest']
    files += ['./icons/' + n for n in sorted(os.listdir(os.path.join(out, 'icons')))]
    sw = SW_TEMPLATE.replace('__CACHE__', f'crosstown-heat-{VERSION}-{h}').replace('__FILES__', json.dumps(files, indent=2))
    with open(os.path.join(out, 'sw.js'), 'w', encoding='utf-8') as f:
        f.write(sw)
    with open(os.path.join(out, '.nojekyll'), 'w') as f:
        f.write('')
    print(f'www: {len(js) / 1024:.0f} KB bundle')


def build_artifact():
    js = bundle('dist/artifact.js', external_three=True)
    js = js.replace('</script', '<\\/script')
    with open(os.path.join(WEB, 'index.html'), encoding='utf-8') as f:
        html = f.read()
    # the artifact host supplies doctype/html/head/body, charset and viewport
    html = re.sub(r'<!doctype html>\s*', '', html, flags=re.I)
    html = re.sub(r'</?html[^>]*>\s*', '', html)
    html = re.sub(r'</?head>\s*', '', html)
    html = re.sub(r'</?body>\s*', '', html)
    html = re.sub(r'<meta charset="utf-8">\s*', '', html)
    html = re.sub(r'<meta name="viewport"[^>]*>\s*', '', html)
    html = re.sub(r'<link rel="(manifest|icon)"[^>]*>\s*', '', html)
    html = re.sub(r'<meta name="(mobile-web-app-capable|apple-mobile-web-app-capable)"[^>]*>\s*', '', html)
    html = re.sub(r'<script type="importmap">.*?</script>',
                  '<script type="importmap">{"imports":{"three":"' + THREE_CDN + '"}}</script>', html, flags=re.S)
    html = html.replace('<script type="module" src="./js/main.js"></script>', '<script type="module">\n' + js + '\n</script>')
    path = os.path.join(DIST, 'artifact.html')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(html)
    os.remove(os.path.join(ROOT, 'dist', 'artifact.js'))
    print(f'artifact: {os.path.getsize(path) / 1024:.0f} KB')


SW_TEMPLATE = """// Offline cache for the installed web app (generated by tools/build.py)
const CACHE = '__CACHE__';
const FONT_CACHE = 'crosstown-heat-fonts';
const FILES = __FILES__;

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE && k !== FONT_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.hostname.startsWith('fonts.g')) {
    e.respondWith(caches.open(FONT_CACHE).then(async (c) => {
      const hit = await c.match(req);
      if (hit) return hit;
      const res = await fetch(req);
      if (res.ok || res.type === 'opaque') c.put(req, res.clone());
      return res;
    }));
    return;
  }
  if (url.origin !== location.origin) return;
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
"""


def main():
    os.makedirs(DIST, exist_ok=True)
    build_www()
    build_artifact()


if __name__ == '__main__':
    main()
